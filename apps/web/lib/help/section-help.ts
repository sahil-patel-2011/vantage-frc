/**
 * Section help — how / why / when for every workbench and major tool.
 *
 * This is the in-app answer to "what is this screen for and when do I use it",
 * rendered inline by `components/help-tip.tsx` beside the hub tab bar and in full
 * on /docs. It is deliberately NOT prose: one sentence of what, one sentence of
 * why, the season moment, and at most five numbered steps.
 *
 * Rules for entries:
 * - Describe only what the surface actually does today. No roadmap, no invented
 *   capabilities, no fabricated metrics (the product itself does not fill in data,
 *   and neither does its help).
 * - `id` is `${hub}.${tabId}` so duplicate tab ids across hubs (impact, code,
 *   batteries, fmea…) stay distinct.
 * - Long-form tutorials still live in `articles.ts`; this registry is the
 *   task-first layer on top of it.
 */

