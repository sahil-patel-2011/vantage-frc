const BY_ID = new Map<string, SectionHelpEntry>(SECTION_HELP.map((entry) => [entry.id, entry]));
const BY_HUB_TAB = new Map<string, SectionHelpEntry>(
  SECTION_HELP.map((entry) => [`${entry.hub}.${entry.tab}`, entry]),
);

export function sectionHelpById(id: string): SectionHelpEntry | undefined {
  return BY_ID.get(id);
}

/** The entry for a hub tab, or undefined when that tab has no help yet. */
export function sectionHelpFor(
  hub: SectionHelpHubId | string | null | undefined,
  tab: string | null | undefined,
): SectionHelpEntry | undefined {
  if (!hub || !tab) return undefined;
  return BY_HUB_TAB.get(`${hub}.${tab}`);
}

export function sectionHelpForHub(hub: SectionHelpHubId): SectionHelpEntry[] {
  return SECTION_HELP.filter((entry) => entry.hub === hub);
}

export function sectionHelpForMoment(moment: SeasonMoment): SectionHelpEntry[] {
  return SECTION_HELP.filter((entry) => entry.moments.includes(moment));
}

export function seasonMomentLabel(moment: SeasonMoment): string {
  return SEASON_MOMENTS.find((entry) => entry.id === moment)?.label ?? moment;
}
