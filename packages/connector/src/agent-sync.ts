export type AgentSyncTargets = { claude: boolean; cursor: boolean };

export async function detectAgentTargets(fs: FileSystemLike, dir: string): Promise<AgentSyncTargets> {
  return {
    claude: (await dirExists(fs, joinPath(dir, ".claude"))) || (await fileExists(fs, joinPath(dir, "CLAUDE.md"))),
    cursor: await dirExists(fs, joinPath(dir, ".cursor")),
  };
}

type WriteOutcome = "written" | "updated" | "unchanged";

async function writeManaged(fs: FileSystemLike, path: string, content: string): Promise<WriteOutcome> {
  const existing = await readIfExists(fs, path);
  if (existing === content) return "unchanged";
  const parent = path.split("/").slice(0, -1).join("/");
  if (parent) await fs.mkdir(parent, { recursive: true });
  await fs.writeFile(path, content);
  return existing === null ? "written" : "updated";
}

/**
 * Remove stale .mdc files from the managed Cursor rules folder. Only files
 * carrying the generated banner are ever deleted — a user-authored file that
 * strayed into .cursor/rules/vantage/ is left alone and reported.
 */
export async function pruneManagedMdcDir(
  fs: FileSystemLike,
  dirPath: string,
  keep: Set<string>,
): Promise<{ pruned: string[]; kept: string[] }> {
  const pruned: string[] = [];
  const kept: string[] = [];
  let entries: string[];
  try {
    entries = await fs.readdir(dirPath);
  } catch {
    return { pruned, kept };
  }
  for (const entry of entries) {
    if (!entry.endsWith(".mdc") || keep.has(entry)) continue;
    const fullPath = joinPath(dirPath, entry);
    const content = await readIfExists(fs, fullPath);
    if (content === null || !content.includes(CURSOR_GENERATED_BANNER)) {
      kept.push(entry);
      continue;
    }
    await fs.rm(fullPath);
    pruned.push(entry);
  }
  return { pruned, kept };
}

export type AgentSyncSummary = string[];

/**
 * Materialize a bundle into one repository directory for the given targets.
 * Same file layout as `vantage-cad agent sync` so the two tools can hand off:
 * Claude Code → .claude/agents, .claude/skills, .claude/vantage-team-rules.md,
 * the marked CLAUDE.md import block, namespaced .mcp.json merge, and the
 * NEVER-auto-applied permissions suggestion file. Cursor → managed .mdc rules,
 * skills, and .cursor/mcp.json with the identical vantage-prefix-only rule.
 */
export async function materializeAgentConfig(
  fs: FileSystemLike,
  dir: string,
  bundle: AgentConfigBundle,
  targets: AgentSyncTargets,
): Promise<AgentSyncSummary> {
  const summary: AgentSyncSummary = [];
  const report = (path: string, outcome: WriteOutcome) => summary.push(`${outcome}: ${path}`);

  const syncMcpFile = async (path: string, label: string) => {
    const merge = mergeMcpServers(await readIfExists(fs, path), bundle.mcpServers, label);
    const changed = merge.added.length + merge.updated.length + merge.removed.length > 0;
    if (!changed) report(label, "unchanged");
    else {
      const parent = path.split("/").slice(0, -1).join("/");
      if (parent) await fs.mkdir(parent, { recursive: true });
      await fs.writeFile(path, merge.json);
      report(label, "updated");
    }
    for (const key of merge.added) summary.push(`+ mcpServers.${key}`);
    for (const key of merge.updated) summary.push(`~ mcpServers.${key}`);
    for (const key of merge.removed) summary.push(`- mcpServers.${key} (no longer in team config)`);
  };

  if (targets.claude) {
    for (const subagent of bundle.subagents) {
      const name = safeConfigName(subagent.name);
      if (!name) {
        summary.push(`skipped: subagent with unsafe name ${JSON.stringify(subagent.name)}`);
        continue;
      }
      report(
        `.claude/agents/${name}.md`,
        await writeManaged(fs, joinPath(dir, ".claude", "agents", `${name}.md`), `${subagent.markdown.trim()}\n`),
      );
    }
    for (const skill of bundle.skills) {
      const name = safeConfigName(skill.name);
      if (!name) {
        summary.push(`skipped: skill with unsafe name ${JSON.stringify(skill.name)}`);
        continue;
      }
      report(
        `.claude/skills/${name}/SKILL.md`,
        await writeManaged(fs, joinPath(dir, ".claude", "skills", name, "SKILL.md"), `${skill.markdown.trim()}\n`),
      );
    }
    const rulesMarkdown = buildTeamRulesMarkdown(bundle);
    if (rulesMarkdown) {
      report(TEAM_RULES_FILE, await writeManaged(fs, joinPath(dir, TEAM_RULES_FILE), rulesMarkdown));
      const claudeMdPath = joinPath(dir, "CLAUDE.md");
      const existing = (await readIfExists(fs, claudeMdPath)) ?? "";
      const next = applyVantageMarkerBlock(existing, buildClaudeMdBlock());
      if (next === existing) report("CLAUDE.md", "unchanged");
      else {
        await fs.writeFile(claudeMdPath, next);
        report("CLAUDE.md", existing ? "updated" : "written");
      }
    } else {
      summary.push("skipped: no team rules published yet");
    }
    if (bundle.mcpServers.length) await syncMcpFile(joinPath(dir, ".mcp.json"), ".mcp.json");
    // Permissions → suggestion file ONLY, never an automatic settings.json merge.
    const suggestion = buildPermissionsSuggestion(bundle);
    if (suggestion) {
      report(
        PERMISSIONS_SUGGESTION_FILE,
        await writeManaged(fs, joinPath(dir, PERMISSIONS_SUGGESTION_FILE), suggestion),
      );
    }
  }

  if (targets.cursor) {
    const wanted = new Set<string>();
    for (const rule of bundle.rules) {
      const file = buildCursorRuleMdc(rule);
      if (!file) {
        summary.push(`skipped: rule ${JSON.stringify(rule.name)} (empty body or unsafe name)`);
        continue;
      }
      wanted.add(file.filename);
      report(
        `${CURSOR_RULES_DIR}/${file.filename}`,
        await writeManaged(fs, joinPath(dir, CURSOR_RULES_DIR, file.filename), file.content),
      );
    }
    // Prune rules that left the team config — banner-carrying files only.
    const prune = await pruneManagedMdcDir(fs, joinPath(dir, CURSOR_RULES_DIR), wanted);
    for (const entry of prune.pruned) summary.push(`removed: ${CURSOR_RULES_DIR}/${entry} (no longer in team config)`);
    for (const entry of prune.kept) summary.push(`left alone: ${CURSOR_RULES_DIR}/${entry} (not generated by sync)`);

    for (const skill of bundle.skills) {
      const folder = cursorSkillFolder(skill.markdown, skill.name);
      if (!folder) {
        summary.push(`skipped: skill with unsafe name ${JSON.stringify(skill.name)}`);
        continue;
      }
      report(
        `${CURSOR_SKILLS_DIR}/${folder}/SKILL.md`,
        await writeManaged(fs, joinPath(dir, CURSOR_SKILLS_DIR, folder, "SKILL.md"), `${skill.markdown.trim()}\n`),
      );
    }
    if (bundle.mcpServers.length) await syncMcpFile(joinPath(dir, CURSOR_MCP_FILE), CURSOR_MCP_FILE);
    // Honest skips: no Cursor-native equivalent — never invent a format.
    for (const subagent of bundle.subagents) {
      summary.push(`skipped: subagent ${subagent.name} (no Cursor equivalent; synced for Claude Code only)`);
    }
    if (bundle.permissions.length) {
      summary.push("skipped: permissions (no Cursor equivalent; see the Claude Code suggestion file)");
    }
  }

  return summary;
}

