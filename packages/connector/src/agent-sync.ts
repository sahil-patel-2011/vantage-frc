export class AgentSyncCapability implements ConnectorCapability {
  readonly id = "agent-sync" as const;
  readonly label = "Team agent config sync";

  private lastSyncAt: number | null = null;
  private lastSummary: AgentSyncSummary = [];
  private lastError: string | null = null;

  constructor(private readonly options: { intervalMs?: number } = {}) {}

  async detect(ctx: CapabilityContext): Promise<CapabilityDetection> {
    const dirs = ctx.config.agentSync?.dirs ?? [];
    if (dirs.length === 0) {
      return {
        available: false,
        detail: "Setup required: add at least one repository directory to sync team agent config into.",
      };
    }
    const missing: string[] = [];
    for (const dir of dirs) {
      if (!(await dirExists(ctx.fs, dir))) missing.push(dir);
    }
    if (missing.length === dirs.length) {
      return { available: false, detail: `None of the configured directories exist: ${missing.join(", ")}` };
    }
    return {
      available: true,
      detail: `Syncing into ${dirs.length - missing.length} of ${dirs.length} configured director${dirs.length === 1 ? "y" : "ies"}.`,
      data: { dirs, missing },
    };
  }

  private async syncOnce(ctx: CapabilityContext): Promise<void> {
    const response = await ctx.transport.getJson(cloudUrl(ctx.config.baseUrl, ctx.endpoints.agentConfigBundle), {
      token: ctx.config.deviceToken,
    });
    if (!response.ok) {
      throw new Error(
        typeof response.data.error === "string" ? response.data.error : `Bundle fetch failed (HTTP ${response.status})`,
      );
    }
    const bundle = parseAgentConfigBundle(response.data);
    const summary: AgentSyncSummary = [];
    for (const dir of ctx.config.agentSync?.dirs ?? []) {
      if (!(await dirExists(ctx.fs, dir))) {
        summary.push(`skipped: ${dir} (directory does not exist)`);
        continue;
      }
      const flag = ctx.config.agentSync?.agent;
      const targets =
        flag === "claude"
          ? { claude: true, cursor: false }
          : flag === "cursor"
            ? { claude: false, cursor: true }
            : flag === "all"
              ? { claude: true, cursor: true }
              : await detectAgentTargets(ctx.fs, dir);
      // Nothing detected and nothing forced: keep the CLI's behavior (Claude Code).
      const effective = targets.claude || targets.cursor ? targets : { claude: true, cursor: false };
      const dirSummary = await materializeAgentConfig(ctx.fs, dir, bundle, effective);
      summary.push(...dirSummary.map((line) => `${dir}: ${line}`));
    }
    this.lastSummary = summary;
    this.lastSyncAt = ctx.clock.now();
    this.lastError = null;
  }

  async start(ctx: CapabilityContext): Promise<void> {
    const interval = this.options.intervalMs ?? AGENT_SYNC_INTERVAL_MS;
    while (!ctx.signal.aborted) {
      try {
        await this.syncOnce(ctx);
        ctx.log(`agent-sync: synced (${this.lastSummary.length} item(s)).`);
      } catch (error) {
        // Sync is a bonus, never a blocker: report and retry on the next interval.
        this.lastError = error instanceof Error ? error.message : String(error);
        ctx.log(`agent-sync: ${this.lastError} (will retry)`);
      }
      await ctx.clock.sleep(interval, ctx.signal);
    }
  }

  async stop(): Promise<void> {
    // The loop honors ctx.signal; nothing else to release.
  }

  status(): CapabilityReport {
    if (this.lastError) return { detail: `Last sync failed: ${this.lastError}`, data: { lastSyncAt: this.lastSyncAt } };
    if (this.lastSyncAt === null) return { detail: "No sync has completed yet." };
    return {
      detail: `Last sync wrote/verified ${this.lastSummary.length} item(s).`,
      data: { lastSyncAt: this.lastSyncAt, summary: this.lastSummary.slice(0, 50) },
    };
  }
}
