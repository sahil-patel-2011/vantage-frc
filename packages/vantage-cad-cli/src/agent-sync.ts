type WriteOutcome = "written" | "updated" | "unchanged" | "dry-run";

async function readIfExists(path: string): Promise<string | null> {
  try {
    return await readFile(path, "utf8");
  } catch {
    return null;
  }
}

async function dirExists(path: string): Promise<boolean> {
  try {
    return (await stat(path)).isDirectory();
  } catch {
    return false;
  }
}

async function fileExists(path: string): Promise<boolean> {
  try {
    return (await stat(path)).isFile();
  } catch {
    return false;
  }
}

/**
 * Remove stale .mdc files from the managed Cursor rules folder. Only files
 * carrying the generated banner are ever deleted — a user-authored file that
 * strayed into .cursor/rules/vantage/ is left alone and reported.
 */
export async function pruneManagedMdcDir(
  dirPath: string,
  keep: Set<string>,
  dryRun: boolean,
): Promise<{ pruned: string[]; kept: string[] }> {
  const pruned: string[] = [];
  const kept: string[] = [];
  let entries: string[];
  try {
    entries = await readdir(dirPath);
  } catch {
    return { pruned, kept };
  }
  for (const entry of entries) {
    if (!entry.endsWith(".mdc") || keep.has(entry)) continue;
    const fullPath = join(dirPath, entry);
    const content = await readIfExists(fullPath);
    if (content === null || !content.includes(CURSOR_GENERATED_BANNER)) {
      kept.push(entry);
      continue;
    }
    if (!dryRun) await rm(fullPath);
    pruned.push(entry);
  }
  return { pruned, kept };
}

async function writeManaged(
  path: string,
  content: string,
  dryRun: boolean,
): Promise<WriteOutcome> {
  const existing = await readIfExists(path);
  if (existing === content) return "unchanged";
  if (dryRun) return "dry-run";
  await mkdir(join(path, ".."), { recursive: true });
  await writeFile(path, content, "utf8");
  return existing === null ? "written" : "updated";
}

export async function fetchAgentConfigBundle(): Promise<AgentConfigBundle> {
  const credential = await loadDeviceCredential();
  if (!credential) throw new Error("Not paired. Run `vantage-cad setup` first.");
  const base = (credential.baseUrl ?? process.env.VANTAGE_URL ?? "http://localhost:3001").replace(/\/$/, "");
  const response = await fetch(`${base}/api/agent-config/bundle`, {
    headers: { authorization: `Bearer ${credential.deviceToken}` },
  });
  const data = (await response.json()) as Record<string, unknown>;
  if (!response.ok) throw new Error(String(data.error ?? `HTTP ${response.status}`));
  if (data.schema !== "vantage.agent-config/v1") {
    throw new Error("Server returned an unknown agent-config bundle schema");
  }
  return data as unknown as AgentConfigBundle;
}

type SyncReporter = (path: string, outcome: WriteOutcome) => void;

/** Namespaced .mcp.json-shaped merge shared by both agents' mcp files. */
async function syncMcpFile(
  path: string,
  label: string,
  servers: AgentConfigBundle["mcpServers"],
  dryRun: boolean,
  summary: string[],
  report: SyncReporter,
): Promise<void> {
  const merge = mergeMcpServers(await readIfExists(path), servers, label);
  const changed = merge.added.length + merge.updated.length + merge.removed.length > 0;
  if (!changed) report(label, "unchanged");
  else if (dryRun) report(label, "dry-run");
  else {
    await writeFile(path, merge.json, "utf8");
    report(label, "updated");
  }
  for (const key of merge.added) summary.push(`    + mcpServers.${key}`);
  for (const key of merge.updated) summary.push(`    ~ mcpServers.${key}`);
  for (const key of merge.removed) summary.push(`    - mcpServers.${key} (no longer in team config)`);
}

async function syncClaude(
  dir: string,
  bundle: AgentConfigBundle,
  dryRun: boolean,
  summary: string[],
  report: SyncReporter,
): Promise<void> {
  summary.push("Claude Code:");

  // Subagents → .claude/agents/<name>.md
  for (const subagent of bundle.subagents) {
    const name = safeConfigName(subagent.name);
    if (!name) {
      summary.push(`  skipped: subagent with unsafe name ${JSON.stringify(subagent.name)}`);
      continue;
    }
    const path = join(dir, ".claude", "agents", `${name}.md`);
    report(`.claude/agents/${name}.md`, await writeManaged(path, `${subagent.markdown.trim()}\n`, dryRun));
  }

  // Skills → .claude/skills/<name>/SKILL.md
  for (const skill of bundle.skills) {
    const name = safeConfigName(skill.name);
    if (!name) {
      summary.push(`  skipped: skill with unsafe name ${JSON.stringify(skill.name)}`);
      continue;
    }
    const path = join(dir, ".claude", "skills", name, "SKILL.md");
    report(`.claude/skills/${name}/SKILL.md`, await writeManaged(path, `${skill.markdown.trim()}\n`, dryRun));
  }

  // Rules → dedicated file + marked @import in CLAUDE.md
  const rulesMarkdown = buildTeamRulesMarkdown(bundle);
  if (rulesMarkdown) {
    report(TEAM_RULES_FILE, await writeManaged(join(dir, TEAM_RULES_FILE), rulesMarkdown, dryRun));
    const claudeMdPath = join(dir, "CLAUDE.md");
    const existing = (await readIfExists(claudeMdPath)) ?? "";
    const next = applyVantageMarkerBlock(existing, buildClaudeMdBlock());
    if (next === existing) report("CLAUDE.md", "unchanged");
    else if (dryRun) report("CLAUDE.md", "dry-run");
    else {
      await writeFile(claudeMdPath, next, "utf8");
      report("CLAUDE.md", existing ? "updated" : "written");
    }
  } else {
    summary.push("  skipped: no team rules published yet");
  }

  // MCP servers → namespaced deep merge into .mcp.json
  if (bundle.mcpServers.length) {
    await syncMcpFile(join(dir, ".mcp.json"), ".mcp.json", bundle.mcpServers, dryRun, summary, report);
  }
}

async function syncCursor(
  dir: string,
  bundle: AgentConfigBundle,
  dryRun: boolean,
  summary: string[],
  report: SyncReporter,
): Promise<void> {
  summary.push("Cursor:");

  // Rules → .cursor/rules/vantage/<name>.mdc (one MDC file per rule)
  const wanted = new Set<string>();
  let wroteRule = false;
  for (const rule of bundle.rules) {
    const file = buildCursorRuleMdc(rule);
    if (!file) {
      summary.push(`  skipped: rule ${JSON.stringify(rule.name)} (empty body or unsafe name)`);
      continue;
    }
    wanted.add(file.filename);
    wroteRule = true;
    report(
      `${CURSOR_RULES_DIR}/${file.filename}`,
      await writeManaged(join(dir, CURSOR_RULES_DIR, file.filename), file.content, dryRun),
    );
  }
  if (!wroteRule) summary.push("  skipped: no team rules published yet");

  // Prune rules that left the team config — banner-carrying files only.
  const prune = await pruneManagedMdcDir(join(dir, CURSOR_RULES_DIR), wanted, dryRun);
  for (const entry of prune.pruned) {
    summary.push(`  ${dryRun ? "would remove" : "removed"}: ${CURSOR_RULES_DIR}/${entry} (no longer in team config)`);
  }
  for (const entry of prune.kept) {
    summary.push(`  left alone: ${CURSOR_RULES_DIR}/${entry} (not generated by sync)`);
  }

  // Skills → .cursor/skills/vantage/<name>/SKILL.md (same SKILL.md contract)
  for (const skill of bundle.skills) {
    const folder = cursorSkillFolder(skill.markdown, skill.name);
    if (!folder) {
      summary.push(`  skipped: skill with unsafe name ${JSON.stringify(skill.name)}`);
      continue;
    }
    const path = join(dir, CURSOR_SKILLS_DIR, folder, "SKILL.md");
    report(`${CURSOR_SKILLS_DIR}/${folder}/SKILL.md`, await writeManaged(path, `${skill.markdown.trim()}\n`, dryRun));
  }

  // MCP servers → same namespaced merge, Cursor's file
  if (bundle.mcpServers.length) {
    await syncMcpFile(join(dir, CURSOR_MCP_FILE), CURSOR_MCP_FILE, bundle.mcpServers, dryRun, summary, report);
  }

  // Honest skips: no Cursor-native equivalent — never invent a format.
  for (const subagent of bundle.subagents) {
    summary.push(`  skipped: subagent ${subagent.name} (no Cursor equivalent; synced for Claude Code only)`);
  }
  if (bundle.permissions.length) {
    summary.push("  skipped: permissions (no Cursor equivalent; see the Claude Code suggestion file)");
  }
}

export async function runAgentSync(argv: string[]): Promise<void> {
  const sub = argv[0] ?? "";
  if (sub !== "sync") {
    console.log("vantage-cad agent sync [--dir <repo>] [--agent claude|cursor|all] [--dry-run]");
    console.log("  Sync your team's shared agent configuration into this repository.");
    console.log("  --agent defaults to what the repo already uses (.claude/CLAUDE.md and/or .cursor).");
    return;
  }
  const dirFlag = argv.indexOf("--dir");
  const dir = dirFlag !== -1 && argv[dirFlag + 1] ? argv[dirFlag + 1]! : process.cwd();
  const dryRun = argv.includes("--dry-run");
  const agentFlagIndex = argv.indexOf("--agent");
  const agentFlag = agentFlagIndex !== -1 ? (argv[agentFlagIndex + 1] ?? "") : null;

  const targets = parseAgentTargets(agentFlag, {
    claude: (await dirExists(join(dir, ".claude"))) || (await fileExists(join(dir, "CLAUDE.md"))),
    cursor: await dirExists(join(dir, ".cursor")),
  });

  const bundle = await fetchAgentConfigBundle();
  const summary: string[] = [];
  const report: SyncReporter = (path, outcome) =>
    summary.push(`  ${outcome === "dry-run" ? "would write" : outcome}: ${path}`);

  if (targets.claude) await syncClaude(dir, bundle, dryRun, summary, report);
  if (targets.cursor) await syncCursor(dir, bundle, dryRun, summary, report);

  // Permissions → suggestion file ONLY, never an automatic settings.json merge.
  const suggestion = targets.claude ? buildPermissionsSuggestion(bundle) : null;
  if (suggestion) {
    report(
      PERMISSIONS_SUGGESTION_FILE,
      await writeManaged(join(dir, PERMISSIONS_SUGGESTION_FILE), suggestion, dryRun),
    );
  }

  const targetLabel = [targets.claude ? "Claude Code" : null, targets.cursor ? "Cursor" : null]
    .filter(Boolean)
    .join(" + ");
  console.log(
    `Team agent config${dryRun ? " (dry run)" : ""} for org ${bundle.orgId} → ${targetLabel}${
      targets.source === "detected" ? " (detected)" : targets.source === "default" ? " (default)" : ""
    }:`,
  );
  for (const line of summary) console.log(line);
  if (targets.source !== "flag" && !targets.cursor) {
    console.log("\nUsing Cursor too? Run with --agent cursor (or --agent all) to write .cursor/rules, .cursor/skills, and .cursor/mcp.json.");
  }
  if (suggestion) {
    console.log(
      `\nPermissions were NOT applied automatically. Review ${PERMISSIONS_SUGGESTION_FILE} and merge the rules you agree with into .claude/settings.json yourself.`,
    );
  }
}
