import { join } from "node:path";
import { loadDeviceCredential } from "./secure-store";

/**
 * `vantage-cad agent sync [--dir <repo>] [--agent claude|cursor|all] [--dry-run]`
 *
 * Pulls the team's shared agent configuration (GET /api/agent-config/bundle,
 * authenticated with the same paired device token as every other CLI route).
 * The bundle is scoped server-side to THIS device's user: team-wide items plus
 * items shared with them personally. Sync then materializes it per agent.
 *
 * Claude Code target:
 * - .claude/agents/<name>.md                    one file per subagent
 * - .claude/skills/<name>/SKILL.md              one folder per skill
 * - .claude/vantage-team-rules.md               concatenated team rules
 * - CLAUDE.md                                   an @import line, ONLY between
 *   BEGIN/END VANTAGE markers (idempotent: re-sync replaces the block, never
 *   duplicates, never touches anything outside the markers)
 * - .mcp.json                                   deep-merged; only keys under the
 *   `vantage-` prefix are added/updated/pruned — other servers are never touched
 * - .claude/vantage-permissions.suggested.json  permissions are a security
 *   change, so they are NEVER auto-merged into settings.json; a human applies
 *   the printed suggestion.
 *
 * Cursor target (formats verified 2026-08 against the official docs —
 * https://cursor.com/docs/context/rules, https://cursor.com/docs/context/mcp,
 * https://cursor.com/docs/skills — see apps/web/lib/agent-config/cursor-formats.ts
 * for the full citations):
 * - .cursor/rules/vantage/<name>.mdc            one MDC file per rule
 *   (frontmatter: description / globs / alwaysApply; team rules without path
 *   scopes are alwaysApply: true). Only files inside this managed folder that
 *   carry the generated banner are ever updated or pruned.
 * - .cursor/skills/vantage/<name>/SKILL.md      one folder per skill (Cursor
 *   Agent Skills use the same SKILL.md frontmatter contract)
 * - .cursor/mcp.json                            same mcpServers shape as
 *   .mcp.json; merged with the identical vantage-prefix-only rule
 * - subagents and permissions have no Cursor-native equivalent and are
 *   reported as skipped for the Cursor target (never an invented format).
 *
 * Default targets: whatever is detected in the repo (.claude/ or CLAUDE.md →
 * Claude Code, .cursor/ → Cursor); when nothing is detected, Claude Code —
 * pass --agent to be explicit.
 */

export const VANTAGE_BEGIN_MARKER = "<!-- BEGIN VANTAGE TEAM AGENT CONFIG -->";
export const VANTAGE_END_MARKER = "<!-- END VANTAGE TEAM AGENT CONFIG -->";
export const VANTAGE_MCP_PREFIX = "vantage-";
export const TEAM_RULES_FILE = ".claude/vantage-team-rules.md";
export const PERMISSIONS_SUGGESTION_FILE = ".claude/vantage-permissions.suggested.json";
export const CURSOR_RULES_DIR = ".cursor/rules/vantage";
export const CURSOR_SKILLS_DIR = ".cursor/skills/vantage";
export const CURSOR_MCP_FILE = ".cursor/mcp.json";
/** Marks a file as Vantage-managed: sync only ever prunes files carrying it. */
export const CURSOR_GENERATED_BANNER =
  "<!-- Generated by `vantage-cad agent sync` — edit at /team/agent-config, not here. -->";

export type AgentConfigBundle = {
  schema: string;
  orgId: string;
  generatedAt: string;
  rules: Array<{ name: string; description: string | null; markdown: string; version: number }>;
  subagents: Array<{ name: string; description: string | null; markdown: string; version: number }>;
  mcpServers: Array<{ name: string; description: string | null; entry: Record<string, unknown>; version: number }>;
  permissions: Array<{ name: string; description: string | null; snippet: { allow?: string[]; deny?: string[]; ask?: string[] }; version: number }>;
  skills: Array<{ name: string; description: string | null; markdown: string; version: number }>;
};

const SAFE_NAME = /^[a-z0-9][a-z0-9-]{0,63}$/;

export function safeConfigName(name: string): string | null {
  return SAFE_NAME.test(name) ? name : null;
}

/**
 * Idempotently install `block` between the VANTAGE markers in a CLAUDE.md body.
 * Everything outside the markers is preserved byte-for-byte; a half-present
 * marker pair is an error (never guess at a corrupt file).
 */
export function applyVantageMarkerBlock(existing: string, block: string): string {
  const begin = existing.indexOf(VANTAGE_BEGIN_MARKER);
  const end = existing.indexOf(VANTAGE_END_MARKER);
  const wrapped = `${VANTAGE_BEGIN_MARKER}\n${block.trim()}\n${VANTAGE_END_MARKER}`;
  if (begin === -1 && end === -1) {
    if (!existing) return `${wrapped}\n`;
    return `${existing.replace(/\n*$/, "\n\n")}${wrapped}\n`;
  }
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `CLAUDE.md has a corrupt VANTAGE marker pair (found ${begin === -1 ? "END without BEGIN" : end === -1 ? "BEGIN without END" : "END before BEGIN"}). Fix or remove the markers, then re-run sync.`,
    );
  }
  const before = existing.slice(0, begin);
  const after = existing.slice(end + VANTAGE_END_MARKER.length);
  return `${before}${wrapped}${after}`;
}

export function buildClaudeMdBlock(): string {
  return [
    "Team agent rules synced from Vantage (/team/agent-config).",
    "Do not edit between these markers — `vantage-cad agent sync` rewrites this block.",
    `@${TEAM_RULES_FILE}`,
  ].join("\n");
}

export type RuleScope = {
  body: string;
  description: string | null;
  globs: string[] | null;
  alwaysApply: boolean | null;
};

/**
 * A rules item MAY start with an optional YAML frontmatter block declaring
 * Cursor scoping metadata (description / globs / alwaysApply — the MDC fields
 * from https://cursor.com/docs/context/rules). Claude Code output uses only
 * the body; the Cursor writer turns the metadata into MDC frontmatter.
 * Mirrors parseRuleScope in apps/web/lib/agent-config/formats.ts (this CLI
 * package intentionally has no dependency on the web app).
 */
export function parseRuleScope(markdown: string): RuleScope {
  const normalized = markdown.replace(/\r\n/g, "\n");
  const none: RuleScope = { body: normalized, description: null, globs: null, alwaysApply: null };
  if (!normalized.startsWith("---\n")) return none;
  const end = normalized.indexOf("\n---", 4);
  if (end === -1) return none;
  const rawFields = normalized.slice(4, end);
  const body = normalized.slice(normalized.indexOf("\n", end + 1) + 1);
  const scope: RuleScope = { body, description: null, globs: null, alwaysApply: null };
  const clean = (value: string) => value.trim().replace(/^["']|["']$/g, "");
  const lines = rawFields.split("\n");
  for (let i = 0; i < lines.length; i += 1) {
    const match = /^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/.exec(lines[i]!);
    if (!match) continue;
    const key = match[1]!;
    if (key === "globs" && !match[2]!.trim()) {
      // YAML block list form: globs:\n  - src/**\n  - "**/*.java"
      const list: string[] = [];
      while (i + 1 < lines.length && /^\s+-\s+/.test(lines[i + 1]!)) {
        i += 1;
        list.push(clean(lines[i]!.replace(/^\s+-\s+/, "")));
      }
      scope.globs = list.filter(Boolean).length ? list.filter(Boolean) : null;
      continue;
    }
    const value = clean(match[2]!);
    if (key === "description" && value) scope.description = value;
    else if (key === "globs" && value) {
      // Cursor docs: "Separate multiple patterns with commas."
      const globs = value.split(",").map(clean).filter(Boolean);
      scope.globs = globs.length ? globs : null;
    } else if (key === "alwaysApply") {
      if (value === "true") scope.alwaysApply = true;
      else if (value === "false") scope.alwaysApply = false;
    }
  }
  return scope;
}

export function buildTeamRulesMarkdown(bundle: AgentConfigBundle): string | null {
  const sections = bundle.rules
    // Claude Code gets the rule BODY only — Cursor scoping frontmatter is
    // metadata for .mdc generation, not agent context.
    .map((rule) => ({ name: rule.name, body: parseRuleScope(rule.markdown).body.trim() }))
    .filter((rule) => rule.body)
    .map((rule) => `## ${rule.name}\n\n${rule.body}`);
  if (!sections.length) return null;
  return [
    CURSOR_GENERATED_BANNER,
    "# Team agent rules",
    ...sections,
    "",
  ].join("\n\n");
}

/** YAML double-quoted scalar (JSON string escaping is valid YAML). */
function yamlQuote(value: string): string {
  return JSON.stringify(value);
}

/**
 * One shared rule → one `.cursor/rules/vantage/<name>.mdc` file (MDC format
 * per https://cursor.com/docs/context/rules). Rules without declared globs are
 * team-wide always-on (`alwaysApply: true`); declared globs make the rule
 * Auto Attached; an explicit alwaysApply in the rule's scope frontmatter wins.
 * Cursor docs: "Separate multiple patterns with commas."
 */
export function buildCursorRuleMdc(rule: {
  name: string;
  description: string | null;
  markdown: string;
}): { filename: string; content: string } | null {
  if (!safeConfigName(rule.name)) return null;
  const scope = parseRuleScope(rule.markdown);
  const body = scope.body.trim();
  if (!body) return null;
  const description = scope.description ?? rule.description;
  const alwaysApply = scope.alwaysApply ?? !scope.globs;
  const frontmatter = ["---"];
  if (description) frontmatter.push(`description: ${yamlQuote(description)}`);
  if (scope.globs) frontmatter.push(`globs: ${scope.globs.join(",")}`);
  frontmatter.push(`alwaysApply: ${alwaysApply}`, "---");
  return {
    filename: `${rule.name}.mdc`,
    content: `${frontmatter.join("\n")}\n\n${CURSOR_GENERATED_BANNER}\n\n${body}\n`,
  };
}

/**
 * Cursor requires a skill folder to match the SKILL.md frontmatter `name`
 * ("Must match the parent folder name." — https://cursor.com/docs/skills).
 * Prefer the frontmatter name when filename-safe; fall back to the item name.
 */
export function cursorSkillFolder(markdown: string, itemName: string): string | null {
  const match = /^---\n[\s\S]*?^name:\s*["']?([A-Za-z0-9-]+)["']?\s*$/m.exec(
    markdown.replace(/\r\n/g, "\n"),
  );
  const fromFrontmatter = match?.[1] ?? "";
  if (fromFrontmatter && safeConfigName(fromFrontmatter)) return fromFrontmatter;
  return safeConfigName(itemName);
}

